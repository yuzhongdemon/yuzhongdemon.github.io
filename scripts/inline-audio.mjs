import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const audioDir = resolve(__dirname, '../public/audio');
const outputPath = resolve(__dirname, '../src/components/widget/audio-data.ts');

const configPath = resolve(audioDir, 'playlist.json');
if (!existsSync(configPath)) {
  console.error('Error: playlist.json not found at', configPath);
  process.exit(1);
}
const config = JSON.parse(readFileSync(configPath, 'utf-8'));

const tracks = [];
let skipped = 0;
let totalSize = 0;

for (const item of config) {
  const filePath = resolve(audioDir, item.file);
  if (!existsSync(filePath)) {
    console.warn('  Warning: file not found:', item.file);
    skipped++;
    continue;
  }
  const buffer = readFileSync(filePath);
  const base64 = buffer.toString('base64');
  totalSize += buffer.length;
  tracks.push({ title: item.title, artist: item.artist, data: base64 });
}

if (tracks.length === 0) {
  console.error('Error: no audio files found. Check playlist.json.');
  process.exit(1);
}

const lines = [
  '// Auto-generated by scripts/inline-audio.mjs -- do not edit',
  '',
  'export interface TrackData {',
  '  title: string;',
  '  artist: string;',
  '  data: string;',
  '}',
  '',
  'const _playlist: TrackData[] = [',
];
for (const t of tracks) {
  lines.push('  { title: ' + JSON.stringify(t.title) + ', artist: ' + JSON.stringify(t.artist) + ', data: ' + JSON.stringify(t.data) + ' },');
}
lines.push('];');
lines.push('export default _playlist;');

writeFileSync(outputPath, lines.join('\n'), 'utf-8');
const mb = (totalSize / 1024 / 1024).toFixed(2);
console.log('(' + tracks.length + ' tracks, ' + mb + ' MB)');
if (skipped > 0) console.log('(skipped ' + skipped + ')');
